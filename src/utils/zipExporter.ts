import JSZip from 'jszip';
import { GeneratedIcon } from '../types/favicon';

export interface ZipExportOptions {
  icons: GeneratedIcon[];
  icoBlob: Blob;
  appName?: string;
  themeColor?: string;
}

export function generateWebmanifest(appName = 'IconForge App', themeColor = '#4f46e5'): string {
  const manifest = {
    name: appName,
    short_name: appName,
    icons: [
      {
        src: '/android-chrome-192x192.png',
        sizes: '192x192',
        type: 'image/png',
      },
      {
        src: '/android-chrome-512x512.png',
        sizes: '512x512',
        type: 'image/png',
      },
    ],
    theme_color: themeColor,
    background_color: '#ffffff',
    display: 'standalone',
  };

  return JSON.stringify(manifest, null, 2);
}

export function generateHtmlSnippet(): string {
  return `<!-- Favicon Package generated by IconForge (https://iconforge.app) -->
<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png">
<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png">
<link rel="manifest" href="/site.webmanifest">
<link rel="shortcut icon" href="/favicon.ico">
<meta name="msapplication-TileColor" content="#4f46e5">
<meta name="theme-color" content="#ffffff">`;
}

