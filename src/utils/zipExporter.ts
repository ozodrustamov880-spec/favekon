export async function createAndDownloadZip(options: ZipExportOptions): Promise<void> {
  const zip = new JSZip();

  // Add favicon.ico
  zip.file('favicon.ico', options.icoBlob);

  // Add individual PNG icons
  for (const icon of options.icons) {
    zip.file(icon.name, icon.blob);
  }

  // Add site.webmanifest
  const manifestContent = generateWebmanifest(options.appName, options.themeColor);
  zip.file('site.webmanifest', manifestContent);

  // Add favicon-tags.html
  zip.file('favicon-tags.html', generateHtmlSnippet());

  // Add README.md
  zip.file('README.md', generateReadme(options.appName));

  // Generate ZIP blob
  const zipBlob = await zip.generateAsync({ type: 'blob' });

  // Download ZIP
  triggerDownload(zipBlob, 'iconforge-favicons.zip');
}

export function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

